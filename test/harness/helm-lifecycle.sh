# helm-lifecycle.sh — Helm lifecycle safety acceptance (make test-helm-lifecycle).
#
# Proves the chart's lifecycle contract against the dedicated test cluster:
#   1. install before the registry Secret exists fails on the pre-install
#      validation hook and leaves no running release;
#   2. with the installation-owner cbse-registry-auth copied from the
#      configured helper namespace, `helm install --wait --atomic` reaches a
#      deployed, Ready release;
#   3. Core DB credential data hashes (never contents), PVC identities, and
#      StatefulSet revisions are recorded;
#   4. a marker table/row in the Core DB (no credential echo) survives
#      NATS/Core DB Pod deletion with persistence enabled;
#   5. `helm upgrade --install` with identical values leaves credential
#      hashes and PVC identities unchanged;
#   6. with one digest-pinned SimulationExperiment applied, `helm uninstall`
#      is blocked by the pre-delete experiment guard while the shared stack
#      remains Ready;
#   7. deleting the CR with --wait while the Scenario Manager is alive lets
#      the rerun uninstall succeed;
#   8. the CRD remains, chart workloads/RBAC/ConfigMaps/Services/hooks are
#      gone, and the ruled retained PVCs plus core-db-credentials survive the
#      Helm uninstall;
#   9. the EXIT trap deletes CRs first, then best-effort Helm uninstall, then
#      the harness-owned namespace (removing the retained test data), then
#      releases the smoke Lease. CBSE_KEEP_ON_FAILURE=1 retention follows the
#      existing smoke semantics.
#
# Values are generated by test/harness/generate-helm-values.sh from a
# digest-pinned images.env supplied via HELM_IMAGES_ENV plus the repository
# image lock; the private values file stays in a temp dir (never in
# artifacts, never printed). No images are built in this slice.
#
# Inputs / environment:
#   KUBECTL, KUBECONFIG, HELM (required) pinned kubectl, dedicated cluster
#          kubeconfig, pinned helm.
#   HELM_IMAGES_ENV (required) readable digest-pinned images.env (smoke
#          format: OPERATOR_IMAGE, SM_IMAGE, EDS_IMAGE,
#          EDS_REFERENCE_IMAGE, TRANS_IMAGE, RUNNER_BASE_IMAGE,
#          DETAIL_DB_IMAGE, PPS_IMAGE).
#   RUN_ID   (default timestamp+random; validated as a 1-30 lowercase DNS
#            label) names the ephemeral namespace and Lease holderIdentity.
#   CBSE_KEEP_ON_FAILURE=1  retain the namespace if the run fails.
#   CBSE_KEEP_NAMESPACE=1  retain the namespace unconditionally.
#   CBSE_PULL_SECRET_NAME (default cbse-registry-auth),
#   CBSE_PULL_SECRET_NAMESPACE (default cbse-test-system).
#
# Exit codes:
#   0  full lifecycle acceptance passed.
#   1  a lifecycle assertion failed.
#   2  RUN_ID is not a valid DNS label, or a required input is missing.
#   Other non-zero propagated from preflight/lease/helm via set -e.
#
# Side effects:
#   Creates the ephemeral cbse-e2e-<RUN_ID> namespace, the cbse-smoke-lock
#   Lease, the release and (via the chart) its workloads; copies the
#   installation-owner registry Secret into the run namespace; applies one
#   test SimulationExperiment. Writes preflight.txt, Helm
#   status/history/rc/inventory records, credential hashes, PVC identities,
#   marker evidence, experiment.yaml, and diagnostics under
#   artifacts/test/<RUN_ID>. Never writes the private values file, the
#   images.env, helm get manifest output, or any Secret payload. The finish
#   trap tears the namespace down (CRs first) and releases the Lease unless
#   retention is requested.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
kubectl_bin="${KUBECTL:?KUBECTL is required}"
helm_bin="${HELM:?HELM is required (pinned helm binary)}"
kubeconfig="${KUBECONFIG:?KUBECONFIG must point to the dedicated test-cluster config}"
images_env="${HELM_IMAGES_ENV:?HELM_IMAGES_ENV must point to a readable digest-pinned images.env}"
run_id="${RUN_ID:-$(date -u +%Y%m%d%H%M%S)-$(openssl rand -hex 3)}"
[[ "${run_id}" =~ ^[a-z0-9]([-a-z0-9]{0,28}[a-z0-9])?$ ]] || {
  echo "RUN_ID must be 1-30 lowercase DNS-label characters" >&2
  exit 2
}
[[ -r "${images_env}" ]] || { echo "HELM_IMAGES_ENV is not readable: ${images_env}" >&2; exit 2; }

# Parse the digest-pinned images.env verbatim (KEY=VALUE lines, no shell
# evaluation) into the eight immutable references before any side effect or
# cluster access. The file may carry extra keys; they are ignored. The file
# may be private, so parse errors name the variable only and never echo a
# reference value.
operator_image=""
sm_image=""
eds_image=""
eds_reference_image=""
trans_image=""
runner_base_image=""
detail_db_image=""
pps_image=""
while IFS= read -r line || [[ -n "${line}" ]]; do
  [[ -z "${line}" || "${line}" == \#* ]] && continue
  [[ "${line}" == *=* ]] || { echo "HELM_IMAGES_ENV contains a malformed line (expected KEY=VALUE)" >&2; exit 2; }
  case "${line%%=*}" in
    OPERATOR_IMAGE) operator_image="${line#*=}" ;;
    SM_IMAGE) sm_image="${line#*=}" ;;
    EDS_IMAGE) eds_image="${line#*=}" ;;
    EDS_REFERENCE_IMAGE) eds_reference_image="${line#*=}" ;;
    TRANS_IMAGE) trans_image="${line#*=}" ;;
    RUNNER_BASE_IMAGE) runner_base_image="${line#*=}" ;;
    DETAIL_DB_IMAGE) detail_db_image="${line#*=}" ;;
    PPS_IMAGE) pps_image="${line#*=}" ;;
    *) : ;;
  esac
done <"${images_env}"
check_digest_variable() {
  local name="$1" value="$2"
  [[ "${value}" =~ ^[^@:]+@sha256:[0-9a-f]{64}$ ]] || {
    echo "${name} is missing or not an immutable <repository>@sha256:<64 lowercase hex> reference in HELM_IMAGES_ENV" >&2
    exit 2
  }
}
check_digest_variable "OPERATOR_IMAGE" "${operator_image}"
check_digest_variable "SM_IMAGE" "${sm_image}"
check_digest_variable "EDS_IMAGE" "${eds_image}"
check_digest_variable "EDS_REFERENCE_IMAGE" "${eds_reference_image}"
check_digest_variable "TRANS_IMAGE" "${trans_image}"
check_digest_variable "RUNNER_BASE_IMAGE" "${runner_base_image}"
check_digest_variable "DETAIL_DB_IMAGE" "${detail_db_image}"
check_digest_variable "PPS_IMAGE" "${pps_image}"
export OPERATOR_IMAGE="${operator_image}" SM_IMAGE="${sm_image}" EDS_IMAGE="${eds_image}"
export EDS_REFERENCE_IMAGE="${eds_reference_image}" TRANS_IMAGE="${trans_image}"
export RUNNER_BASE_IMAGE="${runner_base_image}" DETAIL_DB_IMAGE="${detail_db_image}" PPS_IMAGE="${pps_image}"

namespace="cbse-e2e-${run_id}"
project="lifecycle-${run_id}"
release="cbse"
chart="${root}/charts/cbse"
crd_name="simulationexperiments.experiment.cbse.terministic.de"
artifact_dir="${root}/artifacts/test/${run_id}"
pull_secret_name="${CBSE_PULL_SECRET_NAME:-cbse-registry-auth}"
pull_secret_namespace="${CBSE_PULL_SECRET_NAMESPACE:-cbse-test-system}"
tmp="$(mktemp -d)"
lock_acquired=0
namespace_created=0
started_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
mkdir -p "${artifact_dir}"
rc_log="${artifact_dir}/command-rc.txt"
: >"${rc_log}"

fail() {
  echo "helm lifecycle test failed: $*" >&2
  exit 1
}
log_rc() {
  printf '%s rc=%s\n' "$1" "$2" >>"${rc_log}"
}

# finish is the EXIT trap: diagnose, write summary.json, then perform the
# CRs-first teardown (delete SimulationExperiments and wait for finalizers,
# best-effort Helm uninstall, namespace deletion) and release the
# cbse-smoke-lock Lease if this run still holds it. Retention honors
# CBSE_KEEP_NAMESPACE / CBSE_KEEP_ON_FAILURE with the existing smoke
# semantics.
finish() {
  status=$?
  set +e

  if (( namespace_created == 1 )); then
    KUBECTL="${kubectl_bin}" KUBECONFIG="${kubeconfig}" RUN_ID="${run_id}" \
      CBSE_TEST_NAMESPACE="${namespace}" CBSE_ARTIFACT_DIR="${artifact_dir}" \
      "${root}/test/harness/diagnose.sh"
  fi

  result="passed"
  if (( status != 0 )); then result="failed"; fi
  finished_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  cat >"${artifact_dir}/summary.json" <<EOF
{"run_id":"${run_id}","namespace":"${namespace}","release":"${release}","installer":"helm-lifecycle","result":"${result}","started_at":"${started_at}","finished_at":"${finished_at}"}
EOF

  if (( namespace_created == 1 )); then
    if [[ "${CBSE_KEEP_NAMESPACE:-0}" == "1" ]]; then
      echo "Retained test run namespace: ${namespace}" >&2
    elif (( status == 0 )) || [[ "${CBSE_KEEP_ON_FAILURE:-0}" != "1" ]]; then
      # CRs first: delete the experiments and wait for the Scenario Manager
      # finalizer to clear while the SM is still alive; a dead SM cannot
      # release its own finalizer and would wedge the namespace deletion.
      if "${kubectl_bin}" --kubeconfig "${kubeconfig}" get crd "${crd_name}" >/dev/null 2>&1; then
        "${kubectl_bin}" --kubeconfig "${kubeconfig}" delete simulationexperiment --all \
          -n "${namespace}" --wait=true --timeout=120s >/dev/null 2>&1 ||
          echo "CR deletion wait timed out; proceeding with best-effort teardown" >&2
      fi
      if "${helm_bin}" list -n "${namespace}" --quiet >/dev/null 2>&1; then
        "${helm_bin}" uninstall "${release}" -n "${namespace}" --timeout 3m >/dev/null 2>&1 ||
          echo "best-effort Helm uninstall failed; proceeding with namespace deletion" >&2
      fi
      "${kubectl_bin}" --kubeconfig "${kubeconfig}" delete namespace "${namespace}" \
        --wait=true --timeout=180s >/dev/null 2>&1 ||
        echo "namespace deletion failed or timed out; manual cleanup required" >&2
    else
      echo "Retained failed run namespace: ${namespace}" >&2
    fi
  fi

  if (( lock_acquired == 1 )); then
    holder="$(${kubectl_bin} --kubeconfig "${kubeconfig}" get lease cbse-smoke-lock -n cbse-test-system -o jsonpath='{.spec.holderIdentity}' 2>/dev/null)"
    if [[ "${holder}" != "${run_id}" ]]; then
      # One retry: a transient API error on the first read must not leak the
      # lease (a held lock refuses every later run until manual release).
      sleep 2
      holder="$(${kubectl_bin} --kubeconfig "${kubeconfig}" get lease cbse-smoke-lock -n cbse-test-system -o jsonpath='{.spec.holderIdentity}' 2>/dev/null)"
    fi
    if [[ "${holder}" == "${run_id}" ]]; then
      "${kubectl_bin}" --kubeconfig "${kubeconfig}" delete lease cbse-smoke-lock -n cbse-test-system --wait=false >/dev/null 2>&1
    fi
  fi
  rm -rf "${tmp}"
  exit "${status}"
}
trap finish EXIT
trap 'exit 130' INT TERM


KUBECTL="${kubectl_bin}" KUBECONFIG="${kubeconfig}" SKIP_BUILD=1 \
  "${root}/test/harness/preflight.sh" | tee "${artifact_dir}/preflight.txt"

# Load the checked-in source-image lock (validated by preflight) so the
# rendered experiment fixture uses the locked BUILDER_IMAGE/POSTGRES_IMAGE.
# shellcheck source=test/harness/image-lock.sh
source "${root}/test/harness/image-lock.sh"
load_image_lock "${root}/test/e2e/images.lock.env"

# --- Lease + namespace --------------------------------------------------------
"${kubectl_bin}" --kubeconfig "${kubeconfig}" create namespace cbse-test-system --dry-run=client -o yaml \
  | "${kubectl_bin}" --kubeconfig "${kubeconfig}" apply -f - >/dev/null
"${kubectl_bin}" --kubeconfig "${kubeconfig}" label namespace cbse-test-system \
  app.kubernetes.io/part-of=cbse cbse.terministic.de/test-infrastructure=true --overwrite >/dev/null

KUBECTL="${kubectl_bin}" KUBECONFIG="${kubeconfig}" RUN_ID="${run_id}" \
  "${root}/test/harness/acquire-lock.sh"
lock_acquired=1

"${kubectl_bin}" --kubeconfig "${kubeconfig}" create namespace "${namespace}" >/dev/null
namespace_created=1
"${kubectl_bin}" --kubeconfig "${kubeconfig}" label namespace "${namespace}" \
  "cbse.terministic.de/managed-run=${run_id}" \
  app.kubernetes.io/part-of=cbse-helm-lifecycle \
  pod-security.kubernetes.io/enforce=privileged \
  pod-security.kubernetes.io/audit=restricted \
  pod-security.kubernetes.io/warn=restricted --overwrite >/dev/null

# --- release values (private, temp-dir only) -----------------------------------
values_file="${tmp}/release-values.yaml"
IMAGES_ENV="${images_env}" OUTPUT="${values_file}" \
  "${root}/test/harness/generate-helm-values.sh"
printf 'sha256 %s  release-values.yaml (hash only; the values file is private and never copied into artifacts)\n' \
  "$(cd "${tmp}" && { command -v sha256sum >/dev/null 2>&1 && sha256sum "${values_file}" || shasum -a 256 "${values_file}"; } | awk '{print $1}')" \
  >"${artifact_dir}/helm-values.sha256"
printf 'components=5 (operator, scenarioManager, nats, coreDatabase, hooks.kubectlImage)\n' \
  >"${artifact_dir}/helm-values.summary"

# --- step 1: install before the registry Secret exists -------------------------
# The run namespace has no cbse-registry-auth yet, so the pre-install
# validation hook Job must fail and --atomic must leave no running release.
install_rc=0
"${helm_bin}" install "${release}" "${chart}" \
  --namespace "${namespace}" --values "${values_file}" \
  --wait --atomic --timeout 10m >"${artifact_dir}/install-attempt-1.txt" 2>&1 || install_rc=$?
log_rc "install-attempt-1 (expected pre-install hook failure)" "${install_rc}"
(( install_rc != 0 )) || fail "step 1: install succeeded without the registry Secret; the pre-install validation hook must fail"
release_status="$("${helm_bin}" status "${release}" -n "${namespace}" -o json 2>/dev/null | jq -r '.info.status // empty' || true)"
[[ -z "${release_status}" || "${release_status}" != "deployed" ]] ||
  fail "step 1: a deployed release exists after the expected hook failure"
validation_failed="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" get job cbse-hook-registry-validation \
  -n "${namespace}" -o jsonpath='{.status.failed}' 2>/dev/null || true)"
[[ "${validation_failed}" == "1" ]] ||
  fail "step 1: the registry validation hook Job did not fail (status.failed=${validation_failed:-absent})"
echo "step 1 ok: install blocked by the pre-install registry validation hook; no running release"

# --- step 2: copy the registry Secret, install --------------------------------
"${kubectl_bin}" --kubeconfig "${kubeconfig}" get secret "${pull_secret_name}" \
  -n "${pull_secret_namespace}" -o json \
  | jq 'del(.metadata.namespace, .metadata.resourceVersion, .metadata.uid, .metadata.creationTimestamp, .metadata.managedFields, .metadata.ownerReferences)' \
  | "${kubectl_bin}" --kubeconfig "${kubeconfig}" apply -n "${namespace}" -f - >/dev/null
echo "registry Secret ${pull_secret_name} copied from the helper namespace (payload not logged)"

install_rc=0
"${helm_bin}" install "${release}" "${chart}" \
  --namespace "${namespace}" --values "${values_file}" \
  --wait --atomic --timeout 10m >"${artifact_dir}/install.txt" 2>&1 || install_rc=$?
log_rc "install (helm install --wait --atomic)" "${install_rc}"
(( install_rc == 0 )) || fail "step 2: helm install failed (see install.txt)"
"${helm_bin}" status "${release}" -n "${namespace}" >"${artifact_dir}/helm-status.txt" 2>&1
"${helm_bin}" history "${release}" -n "${namespace}" >"${artifact_dir}/helm-history.txt" 2>&1
"${kubectl_bin}" --kubeconfig "${kubeconfig}" get all,configmaps,secrets,serviceaccounts,roles,rolebindings,pods,pvc,jobs \
  -n "${namespace}" >"${artifact_dir}/objects-inventory.txt" 2>&1 || true
"${kubectl_bin}" --kubeconfig "${kubeconfig}" wait --for=condition=Ready pod \
  -l app=scenario-manager -n "${namespace}" --timeout=240s >/dev/null
echo "step 2 ok: release deployed, shared stack Ready"

# --- step 3: record credential hashes, PVC identities, STS revisions ----------
record_state() {
  local prefix="$1"
  local f
  f="${artifact_dir}/credentials-hash-${prefix}.txt"
  : >"${f}"
  local key b64 h
  for key in SCENARIO_MANAGER_CORE_DB_USER SCENARIO_MANAGER_CORE_DB_PASSWORD; do
    b64="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" get secret core-db-credentials \
      -n "${namespace}" -o jsonpath="{.data.${key}}" 2>/dev/null)" ||
      fail "step 3: could not read core-db-credentials key ${key}"
    h="$(printf '%s' "${b64}" | { command -v sha256sum >/dev/null 2>&1 && sha256sum || shasum -a 256; } | awk '{print $1}')"
    printf '%s sha256=%s\n' "${key}" "${h}" >>"${f}"
  done
  "${kubectl_bin}" --kubeconfig "${kubeconfig}" get pvc -n "${namespace}" -o json \
    | jq -r '.items[] | [.metadata.name, .metadata.uid, (.spec.resources.requests.storage // "-")] | @tsv' \
    >"${artifact_dir}/pvc-identities-${prefix}.txt"
  : >"${artifact_dir}/sts-revisions-${prefix}.txt"
  local sts
  for sts in core-db sm-eds-nats; do
    local revision
    revision="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" get pods -n "${namespace}" \
      -l "app=${sts}" -o jsonpath='{.items[0].metadata.labels.controller-revision-hash}' 2>/dev/null || true)"
    printf 'statefulset/%s controller-revision-hash=%s\n' "${sts}" "${revision:-unknown}" >>"${artifact_dir}/sts-revisions-${prefix}.txt"
  done
}
record_state "after-install"
echo "step 3 ok: credential hashes, PVC identities, and StatefulSet revisions recorded"

# --- step 4: Core DB marker, Pod deletion, survival ----------------------------
marker_script="$(cat <<'SQL'
psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 \
  -c 'CREATE TABLE IF NOT EXISTS cbse_h4_lifecycle_marker (id integer PRIMARY KEY, note text)' \
  -c "INSERT INTO cbse_h4_lifecycle_marker (id, note) VALUES (1, 'h4-lifecycle-marker') ON CONFLICT (id) DO NOTHING"
SQL
)"
"${kubectl_bin}" --kubeconfig "${kubeconfig}" exec -n "${namespace}" pod/core-db-0 -- sh -c "${marker_script}" \
  >"${artifact_dir}/marker-check.txt" 2>&1 || fail "step 4: marker table/row creation failed (see marker-check.txt)"
check_script="$(cat <<'SQL'
psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 -tAc 'SELECT id || '"'"'|'"'"' || note FROM cbse_h4_lifecycle_marker WHERE id = 1'
SQL
)"
marker_before="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" exec -n "${namespace}" pod/core-db-0 -- sh -c "${check_script}" 2>/dev/null | tail -n 1 || true)"
[[ "${marker_before}" == "1|h4-lifecycle-marker" ]] ||
  fail "step 4: marker row missing before Pod deletion (got: ${marker_before:-empty})"

"${kubectl_bin}" --kubeconfig "${kubeconfig}" delete pod -n "${namespace}" -l app=sm-eds-nats --wait=true --timeout=180s >/dev/null
"${kubectl_bin}" --kubeconfig "${kubeconfig}" delete pod -n "${namespace}" -l app=core-db --wait=true --timeout=180s >/dev/null
"${kubectl_bin}" --kubeconfig "${kubeconfig}" rollout status statefulset/sm-eds-nats -n "${namespace}" --timeout=240s >/dev/null
"${kubectl_bin}" --kubeconfig "${kubeconfig}" rollout status statefulset/core-db -n "${namespace}" --timeout=240s >/dev/null

marker_after="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" exec -n "${namespace}" pod/core-db-0 -- sh -c "${check_script}" 2>/dev/null | tail -n 1 || true)"
[[ "${marker_after}" == "1|h4-lifecycle-marker" ]] ||
  fail "step 4: marker row did not survive the Core DB Pod restart (got: ${marker_after:-empty})"
nats_health="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" exec -n "${namespace}" pod/sm-eds-nats-0 \
  -- wget -qO- 'http://127.0.0.1:8222/healthz?js-enabled-only=true' 2>/dev/null || true)"
[[ "${nats_health}" == *'"status":"ok"'* ]] ||
  fail "step 4: NATS JetStream readiness probe failed after Pod restart (got: ${nats_health:-empty})"
printf 'marker row before Pod deletion: %s\nmarker row after Pod deletion: %s\nnats jetstream health after restart: %s\n' \
  "${marker_before}" "${marker_after}" "${nats_health}" >"${artifact_dir}/marker-survival.txt"
echo "step 4 ok: marker and JetStream survived the Pod deletion with persistence enabled"

# --- step 5: upgrade with identical values ------------------------------------
upgrade_values_file="${tmp}/release-values-upgrade.yaml"
IMAGES_ENV="${images_env}" OUTPUT="${upgrade_values_file}" \
  "${root}/test/harness/generate-helm-values.sh"
upgrade_rc=0
"${helm_bin}" upgrade --install "${release}" "${chart}" \
  --namespace "${namespace}" --values "${upgrade_values_file}" \
  --wait --atomic --timeout 10m >"${artifact_dir}/upgrade.txt" 2>&1 || upgrade_rc=$?
log_rc "upgrade (helm upgrade --install --wait --atomic)" "${upgrade_rc}"
(( upgrade_rc == 0 )) || fail "step 5: helm upgrade failed (see upgrade.txt)"
"${helm_bin}" status "${release}" -n "${namespace}" >"${artifact_dir}/helm-status.txt" 2>&1
"${helm_bin}" history "${release}" -n "${namespace}" >"${artifact_dir}/helm-history.txt" 2>&1
"${kubectl_bin}" --kubeconfig "${kubeconfig}" wait --for=condition=Ready pod \
  -l app=scenario-manager -n "${namespace}" --timeout=240s >/dev/null
record_state "after-upgrade"
diff -u "${artifact_dir}/credentials-hash-after-install.txt" "${artifact_dir}/credentials-hash-after-upgrade.txt" \
  >"${artifact_dir}/credentials-hash-diff.txt" || fail "step 5: Core DB credential data changed across the upgrade"
diff -u "${artifact_dir}/pvc-identities-after-install.txt" "${artifact_dir}/pvc-identities-after-upgrade.txt" \
  >"${artifact_dir}/pvc-identities-diff.txt" || fail "step 5: PVC identities changed across the upgrade"
echo "step 5 ok: upgrade stable — credential hashes and PVC identities unchanged"

# --- step 6: experiment fixture + expected blocked uninstall -------------------
sed \
  -e "s|CBSE_NAMESPACE|${namespace}|g" \
  -e "s|CBSE_PROJECT|${project}|g" \
  -e "s|CBSE_RUN_ID|${run_id}|g" \
  -e "s|CBSE_SUPPORT_IMAGE|${EDS_REFERENCE_IMAGE}|g" \
  -e "s|CBSE_EDS_REFERENCE_IMAGE|${EDS_REFERENCE_IMAGE}|g" \
  -e "s|CBSE_PPS_IMAGE|${PPS_IMAGE}|g" \
  -e "s|CBSE_TRANS_IMAGE|${TRANS_IMAGE}|g" \
  -e "s|CBSE_BUILDER_IMAGE|${BUILDER_IMAGE}|g" \
  -e "s|CBSE_RUNNER_BASE_IMAGE|${RUNNER_BASE_IMAGE}|g" \
  -e "s|CBSE_RUNNER_REPOSITORY|${CBSE_RUNNER_REPOSITORY:-registry.unibw.de/i31bdase/cbse-test-runner}|g" \
  -e "s|CBSE_DETAIL_DB_IMAGE|${DETAIL_DB_IMAGE}|g" \
  -e "s|CBSE_POSTGRES_IMAGE|${POSTGRES_IMAGE}|g" \
  "${root}/test/e2e/manifests/experiment.yaml" >"${artifact_dir}/experiment.yaml"
"${kubectl_bin}" --kubeconfig "${kubeconfig}" apply -f "${artifact_dir}/experiment.yaml" >/dev/null

blocked_rc=0
"${helm_bin}" uninstall "${release}" -n "${namespace}" --timeout 5m \
  >"${artifact_dir}/uninstall-blocked.txt" 2>&1 || blocked_rc=$?
log_rc "uninstall-attempt-1 (expected pre-delete guard failure)" "${blocked_rc}"
(( blocked_rc != 0 )) || fail "step 6: uninstall succeeded while a SimulationExperiment still exists"
guard_failed="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" get job cbse-hook-experiment-guard \
  -n "${namespace}" -o jsonpath='{.status.failed}' 2>/dev/null || true)"
[[ "${guard_failed}" == "1" ]] ||
  fail "step 6: the pre-delete guard Job did not fail (status.failed=${guard_failed:-absent})"
"${helm_bin}" status "${release}" -n "${namespace}" >"${artifact_dir}/helm-status.txt" 2>&1
release_status="$("${helm_bin}" status "${release}" -n "${namespace}" -o json 2>/dev/null | jq -r '.info.status // empty' || true)"
# Helm 3 marks the release uninstalling before the pre-delete hooks run and
# does not revert that status when the guard fails; the release and its
# objects must still exist (absent/deleted would mean the guard did not block).
[[ "${release_status}" == "deployed" || "${release_status}" == "uninstalling" ]] ||
  fail "step 6: the release no longer exists after the blocked uninstall (status=${release_status:-absent})"
for workload in deployment/experiment-operator deployment/scenario-manager statefulset/core-db statefulset/sm-eds-nats; do
  "${kubectl_bin}" --kubeconfig "${kubeconfig}" rollout status "${workload}" -n "${namespace}" --timeout=240s >/dev/null \
    || fail "step 6: ${workload} is not Ready after the blocked uninstall"
done
echo "step 6 ok: uninstall blocked by the pre-delete guard; shared stack remains Ready"

# --- step 7: CR deletion while the SM is alive, then successful uninstall ------
# The SM attaches its cleanup finalizer on reconcile. Wait for it so the
# delete below exercises the finalizer-release path instead of a finalizer-less
# immediate delete (the CRs-first cleanup ordering relies on that finalizer).
finalizers=""
for _ in $(seq 1 60); do
  finalizers="$("${kubectl_bin}" --kubeconfig "${kubeconfig}" get simulationexperiment "${project}" -n "${namespace}" -o jsonpath='{.metadata.finalizers}' 2>/dev/null || true)"
  [[ -n "${finalizers}" && "${finalizers}" != "null" ]] && break
  sleep 2
done
[[ -n "${finalizers}" && "${finalizers}" != "null" ]] ||
  fail "step 7: the Scenario Manager did not attach its cleanup finalizer to the SimulationExperiment within 120s"
delete_rc=0
"${kubectl_bin}" --kubeconfig "${kubeconfig}" delete simulationexperiment "${project}" \
  -n "${namespace}" --wait=true --timeout=300s >/dev/null 2>&1 || delete_rc=$?
log_rc "simulationexperiment delete --wait (Scenario Manager finalizer)" "${delete_rc}"
(( delete_rc == 0 )) || fail "step 7: the SimulationExperiment did not delete with --wait (finalizer not released by the live SM)"
uninstall_rc=0
"${helm_bin}" uninstall "${release}" -n "${namespace}" --timeout 5m \
  >"${artifact_dir}/uninstall.txt" 2>&1 || uninstall_rc=$?
log_rc "uninstall (expected success)" "${uninstall_rc}"
(( uninstall_rc == 0 )) || fail "step 7: helm uninstall failed after CR deletion (see uninstall.txt)"
echo "step 7 ok: CR deleted while the SM was alive; uninstall succeeded"

