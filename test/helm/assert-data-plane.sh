# render_one TEMPLATE OUTPUT — render exactly one chart template file.
render_one() {
  local template="$1" output="$2"
  "${CBSE_HELM_BIN}" template cbse "${CBSE_HELM_CHART}" \
    --namespace cbse-system -f "${CBSE_HELM_VALUES}" \
    --show-only "templates/${template}" >"${output}"
}

# render_one_extra TEMPLATE EXTRA_VALUES OUTPUT — render one template with
# an extra values file (for branch renders); failures propagate.
render_one_extra() {
  local template="$1" extra_values="$2" output="$3"
  "${CBSE_HELM_BIN}" template cbse "${CBSE_HELM_CHART}" \
    --namespace cbse-system -f "${CBSE_HELM_VALUES}" -f "${extra_values}" \
    --show-only "templates/${template}" >"${output}"
}

# render_full OUTPUT [EXTRA_VALUES] — render every template document
# (no CRDs) with the fixture values and an optional extra values file.
render_full() {
  local output="$1" extra_values="${2:-}"
  if [[ -n "${extra_values}" ]]; then
    "${CBSE_HELM_BIN}" template cbse "${CBSE_HELM_CHART}" \
      --namespace cbse-system -f "${CBSE_HELM_VALUES}" -f "${extra_values}" >"${output}"
  else
    "${CBSE_HELM_BIN}" template cbse "${CBSE_HELM_CHART}" \
      --namespace cbse-system -f "${CBSE_HELM_VALUES}" >"${output}"
  fi
}

# spec_block FILE KEY — print one spec-level block: the two-space KEY line
# and every deeper-indented line until the next two-space key.
spec_block() {
  local file="$1" key="  ${2}:"
  awk -v key="${key}" '
    $0 == key { f = 1; print; next }
    f && /^  [^[:space:]]/ { f = 0 }
    f { print }
  ' "${file}"
}

# doc_named FILE NAME — print the rendered document(s) whose metadata name
# is exactly NAME, from a multi-document render.
doc_named() {
  local file="$1" target="$2"
  awk -v target="${target}" '
    function flush() { if (keep) printf "%s", buf; buf = ""; keep = 0; decided = 0 }
    /^---$/ { flush(); next }
    {
      buf = buf $0 "\n"
      if (!decided && $0 ~ /^  name: /) {
        decided = 1
        n = $0
        sub(/^  name: /, "", n)
        keep = (n == target)
      }
    }
    END { flush() }
  ' "${file}"
}

