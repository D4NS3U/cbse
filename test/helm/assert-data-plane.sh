# --- 6. Data-plane-wide hygiene -------------------------------------------------
# Exactly one Secret document in the whole render, and it is the
# Helm-managed credentials Secret: no NATS credentials Secret, no other
# secret material.
cbse_helm_assert_line_count "rendered Secret documents" \
  "$(grep -c '^kind: Secret' "${full_render}")" 1
grep -Fqx '  name: core-db-credentials' <(doc_named "${full_render}" core-db-credentials)
# The generated user value and password value appear exactly once each,
# inside the Secret document; nothing else in the render carries them.
# (The password is extracted from this same render: every render
# generates its own bytes, so values are never compared across renders.)
pw_b64_full="$(doc_named "${full_render}" core-db-credentials | grep -oE 'SCENARIO_MANAGER_CORE_DB_PASSWORD: [A-Za-z0-9+/]{64}' | awk '{print $2}')"
[[ -n "${pw_b64_full}" ]] || cbse_helm_fail "could not extract the generated password value from the render"
cbse_helm_assert_line_count "generated user value only in the Secret" \
  "$(grep -cF 'Y2JzZQ==' "${full_render}")" 1
cbse_helm_assert_line_count "generated password value only in the Secret" \
  "$(grep -cF "${pw_b64_full}" "${full_render}")" 1
# No literal username value and no non-empty NATS credential anywhere.
cbse_helm_assert_line_count "no literal username value in the render" \
  "$(grep -cE '^[[:space:]]*value: "?cbse"?' "${full_render}" || true)" 0
grep -Fqx '  SCENARIO_MANAGER_NATS_USER: ""' "${full_render}"
grep -Fqx '  SCENARIO_MANAGER_NATS_PASSWORD: ""' "${full_render}"
cbse_helm_assert_line_count "no NATS credential material in the render" \
  "$(grep -vE '^[[:space:]]*#' "${full_render}" | grep -cE '^[[:space:]]*(nats|NATS)[_-]?(credential|user|password|token)[:=]' || true)" 0
